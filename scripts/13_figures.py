# phase 11: figures for the report and a register that maps every headline number to its source file
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import matplotlib.pyplot as plt
import pandas as pd

from gwcache import config

RES = config.path("results")
FIG = config.path("figures")
INK, MUTED, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
# categorical slots of the reference palette, assigned to policies in a fixed order
COLORS = {"P1_fixed": "#2a78d6", "P2_per_intent": "#eb6834", "P3_per_query": "#1baf7a",
          "P5_context": "#eda100", "P4_patterns": "#e87ba4", "P4plus_context_patterns": "#008300"}


# shared axis styling: recessive grid, no top/right spines, muted ticks
def style(ax, title: str, xlabel: str, ylabel: str):
    ax.set_facecolor(SURFACE)
    ax.set_title(title, color=INK, loc="left")
    ax.set_xlabel(xlabel, color=INK)
    ax.set_ylabel(ylabel, color=INK)
    ax.grid(color=GRID, linewidth=0.8)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=MUTED)


# hit rate vs wrong-reuse curves for one evaluation period, with the pre-registered levels marked
def curve_figure(name: str, title: str):
    path = RES / f"{name}.csv"
    if not path.exists():
        return
    curves = pd.read_csv(path)
    fig, ax = plt.subplots(figsize=(8, 5), facecolor=SURFACE)
    for level in config.load()["eval"]["wrong_reuse_levels"]:
        ax.axvline(level * 100, color=MUTED, linewidth=1, linestyle="--")
        ax.text(level * 100, 0.02, f" {int(level * 100)}% level", transform=ax.get_xaxis_transform(), color=MUTED, fontsize=9)
    for policy, color in COLORS.items():
        c = curves[(curves["policy"] == policy) & (curves["hit_rate"] > 0)].sort_values("hit_rate")
        if len(c):
            ax.plot(c["wrong_reuse"] * 100, c["hit_rate"] * 100, color=color, linewidth=2, label=policy)
    style(ax, title, "Wrong-reuse rate (% of served answers not acceptable)", "Hit rate (% of all requests)")
    ax.set_xlim(0, 50)
    ax.set_ylim(bottom=0)
    ax.legend(frameon=False, labelcolor=INK)
    fig.tight_layout()
    fig.savefig(FIG / f"{name}.png", dpi=200, facecolor=SURFACE)
    plt.close(fig)


# quality vs strong-model share for each router
def routing_figure():
    path = RES / "routing_curves.csv"
    if not path.exists():
        return
    curves = pd.read_csv(path)
    fig, ax = plt.subplots(figsize=(8, 5), facecolor=SURFACE)
    for router, color in zip(["per_query", "context", "patterns"], ["#1baf7a", "#eda100", "#e87ba4"]):
        c = curves[curves["router"] == router]
        ax.plot(c["strong_share"] * 100, c["quality"] * 100, color=color, linewidth=2, label=router)
    for cap in config.load()["routing"]["strong_share_levels"]:
        ax.axvline(cap * 100, color=MUTED, linewidth=1, linestyle="--")
    style(ax, "Routing: quality vs share sent to the strong model", "Requests sent to the strong model (%)",
          "Quality (% no worse than the strong model)")
    ax.legend(frameon=False, labelcolor=INK)
    fig.tight_layout()
    fig.savefig(FIG / "routing_curves.png", dpi=200, facecolor=SURFACE)
    plt.close(fig)


# markdown index of every result file with its headline numbers, regenerated on every run
def register():
    lines = ["# Results register", "", "Generated by `scripts/13_figures.py`. Every number in the report should trace to a file listed here.", ""]
    for f in sorted(RES.glob("*.json")):
        lines += [f"## {f.name}", "", "```", json.dumps(json.loads(f.read_text(encoding="utf-8")), indent=2, default=str), "```", ""]
    for f in sorted(RES.glob("*.csv")):
        df = pd.read_csv(f)
        lines += [f"- `{f.name}`: {len(df)} rows; columns: {', '.join(df.columns[:8])}{' ...' if len(df.columns) > 8 else ''}"]
    lines += ["", "Figures:"] + [f"- `figures/{f.name}`" for f in sorted(FIG.glob("*.png"))]
    (RES / "REGISTER.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    curve_figure("dev_curves", "Development (dev period): hit rate vs wrong-reuse")
    curve_figure("confirm_curves", "Confirmation: hit rate vs wrong-reuse")
    routing_figure()
    register()
    print(f"figures in {FIG}, register at {RES / 'REGISTER.md'}")


if __name__ == "__main__":
    main()
